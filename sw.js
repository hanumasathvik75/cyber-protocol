// SafeMind Service Worker for Android PWA Installability
const CACHE_NAME = 'safemind-parent-v1';
const ASSETS = [
  '/parent-portal.html',
  '/manifest.json',
  '/icon-192.png',
  '/icon-512.png',
  '/safemind_family.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(ASSETS).catch(() => {});
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      );
    })
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  // Let network handle dynamic API requests (ntfy SSE, etc.)
  if (event.request.url.includes('ntfy.sh') || event.request.url.includes('/api/')) {
    return;
  }
  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      return cachedResponse || fetch(event.request).catch(() => cachedResponse);
    })
  );
});
